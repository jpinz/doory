import { expect, test } from '@playwright/test'
import { click, getDoc, openEditor, openTool, pageObjects, toolbarOf, waitForObjectCount } from './helpers'

test('configures a wheel, spins in editor and presentation, and preserves it in shared view', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await openEditor(page, 'doc=blank')
  await openTool(page, 'elements')
  await expect(page.getByRole('button', { name: 'Add spinning wheel', exact: true })).toHaveCount(0)
  await page.getByTestId('sticker-category').click()
  await expect(page.getByRole('option', { name: 'Interactive', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await openTool(page, 'dynamic')
  await expect(page.getByRole('heading', { name: 'Interactive', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dynamic-panel.png') })
  await page.getByRole('button', { name: 'Add spinning wheel', exact: true }).click()
  await waitForObjectCount(page, 1)
  await toolbarOf(page).getByRole('button', { name: 'Edit wheel slices', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Edit wheel slices', exact: true })
  await form.getByLabel('Content', { exact: true }).nth(0).fill('Coffee')
  await form.getByLabel('Percentage (%)', { exact: true }).nth(0).fill('10')
  await expect(form.getByRole('button', { name: 'Apply', exact: true })).toBeDisabled()
  await form.getByLabel('Percentage (%)', { exact: true }).nth(1).fill('40')
  await form.getByRole('button', { name: 'Apply', exact: true }).click()
  const saved = await getDoc(page)
  await toolbarOf(page).getByRole('button', { name: 'Spin wheel', exact: true }).click()
  await expect(page.getByText(/^Winner:/).first()).toBeVisible()
  expect(await getDoc(page)).toEqual(saved)

  await page.keyboard.press('Shift+P')
  await expect(page.getByTestId('present-frame')).toHaveAttribute('data-ready', 'true')
  await page.getByTestId('present-frame').click()
  await expect(page.getByTestId('present-frame-box').getByRole('status').filter({ hasText: /^Winner:/ })).toBeVisible()
  await expect(page.getByTestId('present-counter')).toHaveText('1 / 1')
  expect(await getDoc(page)).toEqual(saved)
  await page.screenshot({ path: test.info().outputPath('wheel-present.png') })
  await page.keyboard.press('Escape')
  await page.evaluate((doc) => localStorage.setItem('doory.harness.doc', JSON.stringify(doc)), saved)
  await openEditor(page, 'doc=stored&mode=shared-view')
  await expect(page.getByTestId('ed-add-entry-dynamic')).toHaveCount(0)
  const object = (await pageObjects(page))[0]
  await click(page, object.left as number, object.top as number)
  await expect(page.getByText(/^Winner:/).first()).toBeVisible()
  expect(await getDoc(page)).toEqual(saved)
  expect(await page.evaluate(() => window.__doory!.isDirty())).toBe(false)
  expect(await page.evaluate(() => window.__doory!.saves.length)).toBe(0)
  const keyboardSpin = page.getByRole('button', { name: /^Spin wheel:/ })
  await keyboardSpin.focus()
  await keyboardSpin.press('Enter')
  await expect(page.getByText(/^Winner:/).first()).toBeVisible()
})

test('adds a wheel from the Dynamic bottom sheet on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await openEditor(page, 'doc=blank')
  await openTool(page, 'dynamic')
  const sheet = page.getByRole('dialog', { name: 'Dynamic', exact: true })
  await expect(sheet.getByRole('heading', { name: 'Interactive', exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('dynamic-mobile.png') })
  await sheet.getByRole('button', { name: 'Add spinning wheel', exact: true }).click()
  await waitForObjectCount(page, 1)
  await expect(sheet).toHaveCount(0)
  expect((await pageObjects(page))[0].type).toBe('dorywheel')
})

test('animates a spin to a winner without changing the slide or saved document', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await openEditor(page, 'doc=blank')
  await openTool(page, 'dynamic')
  await page.getByRole('button', { name: 'Add spinning wheel', exact: true }).click()
  await waitForObjectCount(page, 1)
  const saved = await getDoc(page)
  await page.keyboard.press('Shift+P')
  const frame = page.getByTestId('present-frame')
  await expect(frame).toHaveAttribute('data-ready', 'true')
  const before = await frame.evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())
  await frame.click()
  await expect(page.getByTestId('present-frame-box').getByRole('status')).toHaveText('Spinning')
  await expect.poll(() => frame.evaluate((canvas: HTMLCanvasElement) => canvas.toDataURL())).not.toBe(before)
  await expect(page.getByTestId('present-frame-box').getByRole('status')).toHaveText(/^Winner:/)
  await expect(page.getByTestId('present-counter')).toHaveText('1 / 1')
  expect(await getDoc(page)).toEqual(saved)
})
